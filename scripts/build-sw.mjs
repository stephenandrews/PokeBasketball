// Generates dist/sw.js after the build: a service worker that precaches the app shell
// (game bundle, CSS, fonts, icons, announcer audio, info pages) and caches every sprite
// on demand plus a background "warm" pass, so the game installs as an app and plays
// fully offline. Runs as the last postbuild step, after the admin build, so it can see
// the whole dist/ and exclude the admin page from the offline bundle.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dist = new URL('../dist/', import.meta.url).pathname;

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const all = walk(dist).map((p) => relative(dist, p).split('\\').join('/'));

// The moderation page stays online-only; build-id.txt is fetched no-store to detect new builds.
const skip = (f) => f === 'sw.js' || f === 'build-id.txt' || f === 'admin.html' || /^assets\/admin-/.test(f);
// Sprites are ~600 small PNGs: cached on demand and warmed in the background instead of
// blocking install on them.
const isWarm = (f) => f.startsWith('sprites/');

const precache = all.filter((f) => !skip(f) && !isWarm(f));
const warm = all.filter((f) => !skip(f) && isWarm(f));

const buildId = readFileSync(join(dist, 'build-id.txt'), 'utf8').trim();

const sw = `// Generated by scripts/build-sw.mjs — do not edit. Build ${buildId}.
const VERSION = ${JSON.stringify(buildId)};
const SHELL = 'pokebball-shell-' + VERSION;
const RUNTIME = 'pokebball-rt'; // survives updates: sprites don't change between builds
const PRECACHE = ${JSON.stringify(precache)};
const WARM = ${JSON.stringify(warm)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('pokebball-shell-') && k !== SHELL).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// The page asks for this once it is idle: pull every sprite into the runtime cache so the
// whole game works offline. Already-cached files are skipped; failures are quietly retried
// on the next visit.
self.addEventListener('message', (e) => {
  if (e.data !== 'warm') return;
  e.waitUntil(caches.open(RUNTIME).then(async (c) => {
    for (const url of WARM) {
      if (await c.match(url)) continue;
      try { await c.add(url); } catch { /* offline or missing: next visit retries */ }
    }
  }));
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return; // Supabase, analytics…: network only
  const path = url.pathname.replace(/^\\//, '');
  if (path === 'build-id.txt' || path === 'admin.html' || path.startsWith('assets/admin-')) return;

  // Pages: network first so a new deploy shows up, cached shell when offline.
  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then((res) => { const copy = res.clone(); caches.open(SHELL).then((c) => c.put(req, copy)); return res; })
        .catch(() => caches.match(req).then((hit) => hit || caches.match('index.html'))),
    );
    return;
  }

  // Everything else (bundle, fonts, sprites, audio): cache first, fill the cache from the
  // network on a miss.
  e.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(RUNTIME).then((c) => c.put(req, copy)); }
      return res;
    })),
  );
});
`;

writeFileSync(join(dist, 'sw.js'), sw);
console.log(`sw: precache ${precache.length} files, warm ${warm.length} sprites (build ${buildId})`);
